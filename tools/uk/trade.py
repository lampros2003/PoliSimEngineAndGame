"""The UK's trade by partner (stage S6.3): the EU, the United States, China and the rest.

    python tools/uk/trade.py           extract models/uk/data/trade_partners.csv

Reads ONS's "UK total trade: all countries, seasonally adjusted" (Open Government Licence
v3.0), which `python tools/uk/pipeline.py fetch trade_partners` downloads, and writes the
2024 exports and imports of goods and services by partner, £ million. `rules()` gives the
model's trade block (trade.toml, written by tools/uk/calibrate.py): exports and imports
by partner at their 2024 shares, each partner's demand growing at its own rate, a
trade-barrier lever per partner, and customs duties.
"""

from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / ".cache" / "uk"
OUT = ROOT / "models" / "uk" / "data" / "trade_partners.csv"
# Model partner: (label, ONS country code; "rest" is the world total less the others)
PARTNERS = [("eu", "The EU", "B5"), ("united_states", "The United States", "US"), ("china", "China", "CN"),
            ("rest_of_world", "The rest of the world", "rest")]
# Annual growth of each partner's demand for UK exports, against world demand's: a
# judgement (the EU's economies grow more slowly than the world's, the US's and China's
# faster); export-weighted, they add to nothing.
GROWTH_PREMIUM = {"eu": -0.005, "united_states": 0.005, "china": 0.015, "rest_of_world": 0.0}
# How trade responds to a barrier (a tariff equivalent, as a share of the price): imports
# from the partner fall by this many times the barrier, and exports to it by the same,
# the partner retaliating in kind. Trade elasticities of 1 to 4 are usual; low and high
# presets span 1 to 3.
RESPONSE = {"low": 1.0, "central": 2.0, "high": 3.0}


def extract() -> dict[str, tuple[float, float]]:
    import openpyxl
    wb = openpyxl.load_workbook(CACHE / "trade_partners.xlsx", read_only=True, data_only=True)
    rows = list(wb["1 Total Trade by Country - A"].iter_rows(values_only=True))
    headers = [i for i, r in enumerate(rows) if r[0] == "Country Code"]
    out = {}
    for which, start in zip(("exports", "imports"), headers):
        column = list(rows[start]).index("2024")
        values = {}
        for r in rows[start + 1:]:
            if r[0] is None or str(r[0]).startswith("Table") or r[0] == "Country Code":
                break
            if isinstance(r[column], (int, float)):
                values[str(r[0])] = float(r[column])
        rest = values["W1"] - sum(values[code] for _, _, code in PARTNERS if code != "rest")
        for name, _, code in PARTNERS:
            out.setdefault(name, {})[which] = rest if code == "rest" else values[code]
    lines = ["partner,exports,imports"] + [f"{n},{out[n]['exports']:.0f},{out[n]['imports']:.0f}" for n, _, _ in PARTNERS]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return {n: (out[n]["exports"], out[n]["imports"]) for n, _, _ in PARTNERS}


def shares(column: str) -> list[float]:
    """Each partner's 2024 share, adjusted in the last place so that they add to exactly 1
    in order, so the base month's exports and imports are unchanged."""
    with open(OUT, newline="", encoding="utf-8") as handle:
        values = [float(r[column]) for r in csv.DictReader(handle)]
    out = [v / sum(values) for v in values]
    out[-1] = 1.0 - sum(out[:-1])
    total = 0.0
    for v in out:
        total += v
    assert total == 1.0, total
    return out


def rules() -> str:
    names = ", ".join(f'"{n}"' for n, _, _ in PARTNERS)
    labels = ", ".join(f'"{label}"' for _, label, _ in PARTNERS)
    levers = ""
    for n, label, _ in PARTNERS:
        levers += f'''
[lever.trade_barrier_{n}]
label = "Trade barriers with {label[0].lower() + label[1:]}"
group = "Trade"
type = "real"
unit = "1"
default = 0.0
range = [0.0, 0.5]
doc = "Tariffs and other barriers on imports from this partner, as a share of their price; it retaliates in kind"
'''
    barrier = "trade_barrier_" + PARTNERS[-1][0]
    for k in range(len(PARTNERS) - 2, -1, -1):
        barrier = f"select(coord(partner) == {k}, trade_barrier_{PARTNERS[k][0]}, {barrier})"
    return f'''# The UK's trade by partner (stage S6.3). GENERATED by tools/uk/calibrate.py from
# tools/uk/trade.py and models/uk/data/trade_partners.csv (ONS, 2024); do not edit.

[dim.partner]
members = [{names}]
labels = [{labels}]

[param.export_share_by_partner]
doc = "Each partner's share of UK exports, 2024"
type = "real"
unit = "1"
dims = ["partner"]
data = "trade/shares.csv"
column = "exports"

[param.import_share_by_partner]
doc = "Each partner's share of UK imports, 2024"
type = "real"
unit = "1"
dims = ["partner"]
data = "trade/shares.csv"
column = "imports"

[param.partner_growth_premium]
doc = "Monthly growth of each partner's demand for UK exports beyond world demand's (a judgement)"
type = "real"
unit = "1"
dims = ["partner"]
data = "trade/shares.csv"
column = "growth_premium"

[param.trade_response]
doc = "How far trade with a partner falls per unit of barrier (imports, and exports through retaliation)"
type = "real"
unit = "1"
low = {RESPONSE["low"]!r}
central = {RESPONSE["central"]!r}
high = {RESPONSE["high"]!r}
{levers}
[state.partner_index]
label = "Demand for UK exports by partner (first month = 1)"
type = "real"
unit = "1"
phase = "accounts"
dims = ["partner"]
initial = 1.0
next = "partner_index * (1.0 + world_growth + partner_growth_premium)"

[var.partner_barrier]
type = "real"
unit = "1"
phase = "spending"
dims = ["partner"]
expr = "{barrier}"

[var.exports_by_partner]
label = "Exports by partner"
type = "real"
unit = "GBP/month"
phase = "spending"
dims = ["partner"]
expr = "exports_base * export_share_by_partner * partner_index * export_demand * max(1.0 - trade_response * partner_barrier, 0.0)"

[var.imports_by_partner]
label = "Imports by partner"
type = "real"
unit = "GBP/month"
phase = "spending"
dims = ["partner"]
expr = "import_share * import_propensity * private_demand * import_share_by_partner * max(1.0 - trade_response * partner_barrier, 0.0)"

[flow.customs_duties]
label = "Customs duties"
from = "firms"
to = "government"
phase = "spending"
expr = "round(sum(partner_barrier * imports_by_partner, partner))"
'''


def write(out_dir: Path) -> str:
    """Writes out_dir/trade/shares.csv and returns trade.toml's text."""
    folder = out_dir / "trade"
    folder.mkdir(parents=True, exist_ok=True)
    ex, im = shares("exports"), shares("imports")
    lines = ["partner,exports,imports,growth_premium"]
    for (n, _, _), e, i in zip(PARTNERS, ex, im):
        monthly = (1 + GROWTH_PREMIUM[n]) ** (1 / 12) - 1
        lines.append(f"{n},{e!r},{i!r},{monthly!r}")
    (folder / "shares.csv").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return rules()


if __name__ == "__main__":
    values = extract()
    for name, (e, i) in values.items():
        print(f"{name:15} exports {e:9,.0f}  imports {i:9,.0f}  (£m, 2024)")
