"""Write the UK's 2024-25 tax and benefit rules for the synthetic households (stage S4.2).

    python tools/uk/make_rules.py          writes models/uk/households/model.toml and rules.toml

The households (built by tools/uk/households.py) become an entity, and these rules run on
every one of them each month. Rates and thresholds are levers, so a player can change them;
their values are 2024-25's, from GOV.UK (Open Government Licence v3.0), checked on
2026-11-14 against:

- Income Tax rates and allowances: current and past (personal allowance £12,570, tapered by
  £1 for every £2 over £100,000; rest of the UK 20% to £37,700 of taxable income, 40% to
  £125,140, 45% above; Scotland 19% to £2,306, 20% to £13,991, 21% to £31,092, 42% to
  £62,430, 45% to £125,140, 48% above);
- Rates and allowances: National Insurance contributions (employees 8% from £242 a week to
  £967, 2% above; employers 13.8% above £175 a week; self-employed Class 4 6% from £12,570
  to £50,270 a year, 2% above);
- Benefit and pension rates 2024 to 2025 (Universal Credit standard allowances £311.68,
  £393.45, £489.23 and £617.60 a month; child element £287.92, £333.33 for a first child
  born before April 2017; work allowance £673 without housing costs; new State Pension
  £221.20 a week);
- Child Benefit rates (2025-26: £26.05 and £17.25 a week, uprated by 1.7% from 2024-25's
  £25.60 and £16.95); the High Income Child Benefit Charge from £60,000 to £80,000.

Simplifications, each listed in models/uk/households/README.md: weekly thresholds are
applied to annual pay (52 weeks); every household with a Universal Credit entitlement
claims it; there is no housing element (no rents yet); the household's first two adults
are the benefit unit; the two-child limit applies; a first child counts as born before
April 2017 when the youngest child is seven or older.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "models" / "uk" / "households"
ADULTS = 4

MODEL = '''# The UK's synthetic households with 2024-25 tax and benefit rules (stage S4.2).
# GENERATED by tools/uk/make_rules.py; do not edit. The records are built by
# tools/uk/households.py from ONS tables; the rules are in rules.toml.

[model]
id = "uk_households"
format = 1
title = "UK households, 2024-25 rules"
currency = "GBP"
minor_units = 100
step = "month"
phases = ["rules", "totals"]
files = ["rules.toml"]

[dim.region]
members = ["north_east", "north_west", "yorkshire", "east_midlands", "west_midlands", "east", "london", "south_east", "south_west", "wales", "scotland", "northern_ireland"]
'''

ENTITY = '''
[entity.household]
data = "{data}"
id = "id"
weight = "weight"

[entity.household.columns.region_code]
type = "int"
unit = "1"

[entity.household.columns.type]
type = "int"
unit = "1"

[entity.household.columns.adults]
type = "int"
unit = "1"

[entity.household.columns.children]
type = "int"
unit = "1"

[entity.household.columns.youngest_child]
type = "int"
unit = "1"

[entity.household.columns.income_decile]
doc = "Decile of equivalised gross income in the base year, 1 to 10"
type = "int"
unit = "1"
'''

# Dimensions for "who gains, who loses": the household's income decile and type.
BREAKDOWNS = '''
[dim.decile]
doc = "Tenths of households by equivalised gross income in the base year, poorest first"
range = [1, 10]
labels = ["Poorest tenth", "Second", "Third", "Fourth", "Fifth", "Sixth", "Seventh", "Eighth", "Ninth", "Richest tenth"]

[dim.household_type]
members = ["one_under_65", "one_65_plus", "unrelated_adults", "couple_no_children", "couple_one_or_two", "couple_three_plus", "couple_grown_children", "lone_parent", "lone_parent_grown", "multi_family"]
labels = ["One adult under 65", "One adult 65 or over", "Unrelated adults", "Couple, no children", "Couple, one or two children", "Couple, three or more children", "Couple with grown-up children", "Lone parent", "Lone parent with grown-up children", "Two or more families"]
'''


def money_column(name: str) -> str:
    return f'''
[entity.household.columns.{name}]
type = "money"
unit = "GBP/year/household"
'''


# Short names for the policy panel, and the panel's group for each lever.
LABELS = {
    "personal_allowance": "Personal allowance", "allowance_taper_start": "Allowance withdrawn above",
    "basic_rate": "Basic rate", "higher_rate": "Higher rate", "additional_rate": "Additional rate",
    "higher_threshold": "Higher rate from", "additional_threshold": "Additional rate from",
    "starter_rate": "Starter rate", "scottish_basic_rate": "Basic rate", "scottish_basic_threshold": "Basic rate from",
    "intermediate_rate": "Intermediate rate", "intermediate_threshold": "Intermediate rate from",
    "scottish_higher_rate": "Higher rate", "scottish_higher_threshold": "Higher rate from",
    "advanced_rate": "Advanced rate", "advanced_threshold": "Advanced rate from",
    "top_rate": "Top rate", "top_threshold": "Top rate from",
    "ni_primary_threshold": "Employees pay from", "ni_upper_limit": "Upper earnings limit",
    "ni_main_rate": "Employee main rate", "ni_upper_rate": "Employee rate above the limit",
    "ni_secondary_threshold": "Employers pay from", "ni_employer_rate": "Employer rate",
    "class4_lower": "Self-employed pay from", "class4_upper": "Self-employed upper limit",
    "class4_main_rate": "Self-employed main rate", "class4_upper_rate": "Self-employed rate above the limit",
    "child_benefit_eldest": "Eldest child", "child_benefit_other": "Each other child",
    "hicbc_start": "Withdrawn from income of", "hicbc_width": "Fully withdrawn over a further",
    "uc_single_young": "Single, under 25", "uc_single": "Single, 25 or over", "uc_couple_young": "Couple, under 25",
    "uc_couple": "Couple, 25 or over", "uc_child": "Per child", "uc_first_child_older": "First child born before 2017",
    "uc_work_allowance": "Work allowance", "uc_taper": "Taper rate", "uc_child_limit": "Children that count",
    "state_pension_age": "State Pension age",
}
GROUPS = [("Income tax", ("personal_allowance", "allowance_taper_start", "basic_rate", "higher_rate", "additional_rate",
                          "higher_threshold", "additional_threshold")),
          ("Scottish income tax", ("starter", "scottish_", "intermediate", "advanced", "top_")),
          ("National Insurance", ("ni_", "class4")),
          ("Child Benefit", ("child_benefit", "hicbc")),
          ("Universal Credit", ("uc_",)),
          ("Pensions", ("state_pension",))]


def group_of(name: str) -> str:
    for group, prefixes in GROUPS:
        if any(name == p or name.startswith(p) for p in prefixes):
            return group
    return ""


def lever(name, value, unit, doc, kind="money", rng=None):
    out = f'''
[lever.{name}]
label = "{LABELS.get(name, name)}"
group = "{group_of(name)}"
type = "{kind}"
unit = "{unit}"
default = {value}
doc = "{doc}"
'''
    if rng:
        out += f"range = [{rng[0]}, {rng[1]}]\n"
    return out


def build(integrated: bool, pay_base: str = "") -> tuple[str, str]:
    """The model file (standalone only) and the rules. Inside the UK model the rules run in
    its income phase, household pay is uprated by the national pay index and pensions by the
    trend index, and the region dimension and the model header come from the UK model."""
    rp, tp = ("income", "income") if integrated else ("rules", "totals")

    def up(name: str) -> str:
        """A money threshold or amount, uprated with prices inside the UK model (unchanged
        policy means thresholds and benefits keep their real value)."""
        return f"round({name} * price_index)" if integrated else name
    model = ENTITY.format(data="households/households.csv" if integrated else "households.csv")
    for i in range(1, ADULTS + 1):
        model += f'''
[entity.household.columns.age{i}]
type = "int"
unit = "1"
'''
        model += money_column(f"earnings{i}") + money_column(f"pension{i}")
        model += f'''
[entity.household.columns.self_employed{i}]
type = "bool"
unit = "1"
'''
    y = "GBP/year/household"
    rules = "# 2024-25 tax and benefit rules. GENERATED by tools/uk/make_rules.py; do not edit.\n"
    if integrated:
        rules += model + f'''
[param.pay_base]
doc = "Private pay per worker in the base month: household pay moves with it"
type = "real"
unit = "GBP/month/person"
value = {pay_base}

[var.pay_uprating]
label = "Household pay relative to the base month"
type = "real"
unit = "1"
phase = "{rp}"
expr = "private_pay_per_worker / pay_base"
'''
    rules += '''
[param.year]
doc = "Months in a year: annual amounts divided by it are monthly"
type = "real"
unit = "month/year"
value = 12.0

[param.scotland_code]
doc = "Position of Scotland in the region dimension"
type = "int"
unit = "1"
value = 10
'''
    rules += lever("personal_allowance", 12570, y, "Income tax personal allowance", rng=(0, 50000))
    rules += lever("allowance_taper_start", 100000, y, "Income above which the personal allowance is withdrawn, £1 for every £2", rng=(0, 1000000))
    for name, value, doc in (("basic_rate", 0.2, "Income tax basic rate, rest of the UK"),
                             ("higher_rate", 0.4, "Income tax higher rate, rest of the UK"),
                             ("additional_rate", 0.45, "Income tax additional rate, rest of the UK")):
        rules += lever(name, value, "1", doc, "real", (0, 1))
    rules += lever("higher_threshold", 37700, y, "Taxable income at which the higher rate starts", rng=(0, 1000000))
    rules += lever("additional_threshold", 125140, y, "Taxable income at which the additional rate starts", rng=(0, 10000000))
    scottish = [("starter", 0.19, 0), ("scottish_basic", 0.20, 2306), ("intermediate", 0.21, 13991),
                ("scottish_higher", 0.42, 31092), ("advanced", 0.45, 62430), ("top", 0.48, 125140)]
    for name, rate, start in scottish:
        rules += lever(f"{name}_rate", rate, "1", f"Scottish income tax {name.replace('_', ' ')} rate", "real", (0, 1))
        if start:
            rules += lever(f"{name}_threshold", start, y, f"Taxable income at which the Scottish {name.replace('_', ' ')} rate starts", rng=(0, 10000000))
    rules += lever("ni_primary_threshold", 12584, y, "Employee National Insurance primary threshold: £242 a week x 52", rng=(0, 100000))
    rules += lever("ni_upper_limit", 50284, y, "Upper earnings limit: £967 a week x 52", rng=(0, 1000000))
    rules += lever("ni_main_rate", 0.08, "1", "Employee National Insurance main rate", "real", (0, 1))
    rules += lever("ni_upper_rate", 0.02, "1", "Employee National Insurance rate above the upper earnings limit", "real", (0, 1))
    rules += lever("ni_secondary_threshold", 9100, y, "Employer National Insurance secondary threshold: £175 a week x 52", rng=(0, 100000))
    rules += lever("ni_employer_rate", 0.138, "1", "Employer National Insurance rate", "real", (0, 1))
    rules += lever("class4_lower", 12570, y, "Self-employed Class 4 lower profits limit", rng=(0, 100000))
    rules += lever("class4_upper", 50270, y, "Self-employed Class 4 upper profits limit", rng=(0, 1000000))
    rules += lever("class4_main_rate", 0.06, "1", "Class 4 main rate", "real", (0, 1))
    rules += lever("class4_upper_rate", 0.02, "1", "Class 4 rate above the upper profits limit", "real", (0, 1))
    rules += lever("child_benefit_eldest", "1331.20", y, "Child Benefit for the eldest child: £25.60 a week x 52", rng=(0, 10000))
    rules += lever("child_benefit_other", "881.40", y, "Child Benefit for each other child: £16.95 a week x 52", rng=(0, 10000))
    rules += lever("hicbc_start", 60000, y, "Income at which the High Income Child Benefit Charge starts", rng=(0, 1000000))
    rules += lever("hicbc_width", 20000, y, "Income over which the charge rises to the whole benefit", rng=(1, 1000000))
    m = "GBP/month/household"
    for name, value, doc in (("uc_single_young", "311.68", "UC standard allowance, single under 25"),
                             ("uc_single", "393.45", "UC standard allowance, single 25 or over"),
                             ("uc_couple_young", "489.23", "UC standard allowance, couple both under 25"),
                             ("uc_couple", "617.60", "UC standard allowance, couple one or both 25 or over"),
                             ("uc_child", "287.92", "UC child element"),
                             ("uc_first_child_older", "333.33", "UC child element for a first child born before April 2017"),
                             ("uc_work_allowance", "673.00", "UC work allowance with children, no housing costs")):
        rules += lever(name, value, m, doc, rng=(0, 10000))
    rules += lever("uc_taper", 0.55, "1", "UC taper: entitlement lost per pound of net earnings above the work allowance", "real", (0, 1))
    rules += lever("uc_child_limit", 2, "1", "Children who attract the UC child element (the two-child limit)", "int", (0, 20))
    rules += lever("state_pension_age", 66, "1", "State Pension age", "int", (55, 75))

    rules += f'''
[table.rest_of_uk_income_tax]
kind = "marginal"
unit = "{y}"
bands = [{{ from = "0", rate = "basic_rate" }}, {{ from = "{up("higher_threshold")}", rate = "higher_rate" }}, {{ from = "{up("additional_threshold")}", rate = "additional_rate" }}]

[table.scottish_income_tax]
kind = "marginal"
unit = "{y}"
bands = [{{ from = "0", rate = "starter_rate" }}, {{ from = "{up("scottish_basic_threshold")}", rate = "scottish_basic_rate" }}, {{ from = "{up("intermediate_threshold")}", rate = "intermediate_rate" }}, {{ from = "{up("scottish_higher_threshold")}", rate = "scottish_higher_rate" }}, {{ from = "{up("advanced_threshold")}", rate = "advanced_rate" }}, {{ from = "{up("top_threshold")}", rate = "top_rate" }}]

[table.employee_ni]
kind = "marginal"
unit = "{y}"
bands = [{{ from = "{up("ni_primary_threshold")}", rate = "ni_main_rate" }}, {{ from = "{up("ni_upper_limit")}", rate = "ni_upper_rate" }}]

[table.employer_ni]
kind = "marginal"
unit = "{y}"
bands = [{{ from = "{up("ni_secondary_threshold")}", rate = "ni_employer_rate" }}]

[table.class4_ni]
kind = "marginal"
unit = "{y}"
bands = [{{ from = "{up("class4_lower")}", rate = "class4_main_rate" }}, {{ from = "{up("class4_upper")}", rate = "class4_upper_rate" }}]
'''

    def var(name, expr, unit=y, kind="money", phase=rp, doc=""):
        out = f'''
[var.{name}]
type = "{kind}"
unit = "{unit}"
phase = "{phase}"
entity = "household"
expr = "{expr}"
'''
        return out + (f'doc = "{doc}"\n' if doc else "")

    for i in range(1, ADULTS + 1):
        if integrated:
            rules += var(f"earn{i}", f"round(earnings{i} * pay_uprating)", doc="Pay or profit now, a year")
            rules += var(f"pens{i}", f"round(pension{i} * trend_index)", doc="Pensions now, a year")
        else:
            rules += var(f"earn{i}", f"earnings{i}", doc="Pay or profit, a year")
            rules += var(f"pens{i}", f"pension{i}", doc="Pensions, a year")
        rules += var(f"pay{i}", f"select(self_employed{i}, 0, earn{i})", doc="Employee pay, a year")
        rules += var(f"profit{i}", f"select(self_employed{i}, earn{i}, 0)", doc="Self-employment profit, a year")
        rules += var(f"income{i}", f"earn{i} + pens{i}", doc="Taxable income, a year")
        rules += var(f"allowance{i}", f"max({up('personal_allowance')} - muldiv(max(income{i} - {up('allowance_taper_start')}, 0), 1, 2), 0)")
        rules += var(f"income_tax{i}", f"select(region_code == scotland_code, marginal(max(income{i} - allowance{i}, 0), scottish_income_tax), marginal(max(income{i} - allowance{i}, 0), rest_of_uk_income_tax))")
        rules += var(f"employee_ni{i}", f"marginal(pay{i}, employee_ni) + marginal(profit{i}, class4_ni)")
        rules += var(f"employer_ni{i}", f"marginal(pay{i}, employer_ni)")
    tax_terms = " + ".join(f"income_tax{i}" for i in range(1, ADULTS + 1))
    rules += var("income_tax_year", tax_terms, doc="Income tax of every adult, a year")
    rules += var("employee_ni_year", " + ".join(f"employee_ni{i}" for i in range(1, ADULTS + 1)))
    rules += var("employer_ni_year", " + ".join(f"employer_ni{i}" for i in range(1, ADULTS + 1)))
    rules += var("top_income", "max(max(income1, income2), max(income3, income4))")
    rules += var("child_benefit_year", f"select(children >= 1, {up('child_benefit_eldest')} + max(children - 1, 0) * {up('child_benefit_other')}, 0)")
    rules += var("hicbc_year", f"round(real(child_benefit_year) * clamp(real(top_income - {up('hicbc_start')}) / real({up('hicbc_width')}), 0.0, 1.0))".replace("real(", "(1.0 * "),
                 doc="High Income Child Benefit Charge, a year")
    # Universal Credit, a month, for working-age benefit units (the first two adults).
    m_unit = "GBP/month/household"
    rules += var("uc_couple_unit", "adults >= 2 and (type >= 3 and type <= 6 or type == 9)", unit="1", kind="bool")
    rules += var("uc_standard", f"select(uc_couple_unit, select(age1 < 25 and age2 < 25, {up('uc_couple_young')}, {up('uc_couple')}), select(age1 < 25, {up('uc_single_young')}, {up('uc_single')}))", unit=m_unit)
    rules += var("uc_children", f"{up('uc_child')} * min(children, uc_child_limit) + select(children >= 1 and youngest_child >= 7, {up('uc_first_child_older')} - {up('uc_child')}, 0)", unit=m_unit)
    rules += var("uc_net_earnings", "round((earn1 - income_tax1 - employee_ni1 + select(uc_couple_unit, earn2 - income_tax2 - employee_ni2, 0)) / year)", unit=m_unit)
    rules += var("uc_unearned", "round((pens1 + select(uc_couple_unit, pens2, 0)) / year)", unit=m_unit)
    rules += var("uc_work_allowed", f"select(children >= 1, {up('uc_work_allowance')}, 0)", unit=m_unit)
    rules += var("universal_credit", "select(age1 < state_pension_age, max(uc_standard + uc_children - round(uc_taper * max(uc_net_earnings - uc_work_allowed, 0)) - uc_unearned, 0), 0)", unit=m_unit,
                 doc="Universal Credit, a month (no housing element)")
    # National totals, a month (money per month for the nation).
    def total(name, expr, label):
        return f'''
[var.{name}]
label = "{label}"
type = "money"
unit = "GBP/month"
phase = "{tp}"
expr = "{expr}"
'''
    adults_net = " + ".join(f"earn{i} + pens{i} - income_tax{i} - employee_ni{i}" for i in range(1, ADULTS + 1))
    rules += var("net_income", f"round(({adults_net} + child_benefit_year - hicbc_year) / year) + universal_credit",
                 unit=m_unit, doc="Income after income tax and National Insurance, with Child Benefit and Universal Credit, a month")
    rules += total("income_tax_total", "round(wsum(household, income_tax_year) / year / household_unit)", "Income tax")
    rules += total("employee_ni_total", "round(wsum(household, employee_ni_year) / year / household_unit)", "National Insurance, employees and self-employed")
    rules += total("employer_ni_total", "round(wsum(household, employer_ni_year) / year / household_unit)", "National Insurance, employers")
    rules += total("child_benefit_total", "round(wsum(household, child_benefit_year - hicbc_year) / year / household_unit)", "Child Benefit, net of the charge")
    rules += total("universal_credit_total", "round(wsum(household, universal_credit) / household_unit)", "Universal Credit")
    rules += f'''
[param.household_unit]
doc = "Turns a sum over households (unit household) into an amount for the nation"
type = "real"
unit = "household/household"
value = 1.0

[var.income_tax_by_region]
type = "real"
unit = "GBP/month"
phase = "{tp}"
dims = ["region"]
expr = "wsum_by(household, income_tax_year, region, region_code) / year / household_unit"
'''
    rules += BREAKDOWNS
    rules += f'''
[var.net_income_average]
label = "Net income per household, all households"
type = "real"
unit = "GBP/month/household"
phase = "{tp}"
expr = "wsum(household, net_income) / wcount(household, true)"
'''
    for dim, key, label in (("decile", "income_decile", "by income decile"), ("household_type", "type", "by household type"),
                            ("region", "region_code", "by region")):
        rules += f'''
[var.net_income_by_{dim}]
label = "Net income per household, {label}"
type = "real"
unit = "GBP/month/household"
phase = "{tp}"
dims = ["{dim}"]
expr = "wsum_by(household, net_income, {dim}, {key}) / wcount_by(household, true, {dim}, {key})"
'''
    return (None if integrated else MODEL + model), rules


def main() -> None:
    model, rules = build(False)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "model.toml").write_text(model, encoding="utf-8", newline="\n")
    (OUT / "rules.toml").write_text(rules, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}/model.toml and rules.toml")


if __name__ == "__main__":
    main()
