"""The statistics audit (stage S15.2, docs/S15-PLAN.md, "Statistics").

    python tools/uk/audit.py            writes models/uk/STATISTICS.md

For every indicator on the 2025 board ([play.web]): how many of the player's policies move it
by a noticeable amount in a year, and what it feeds. Each policy (its first lever) is moved
one step from the 2024 setting in the second month: a level policy one level, any other a
tenth of its range (up, or down where it is at the top), a policy not in force to its first
step. Noticeable: 1% of the indicator's value after twelve months against doing nothing, or
0.1 of a point for a rate (a share below one). What it feeds is read from the model's
formulas: the voters (a value by voter type), a situation, or another indicator, followed
through the values in between.
"""

from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
from engine import Simulation, load_scenario  # noqa: E402

SCENARIO = ROOT / "models" / "uk" / "scenarios" / "2025.toml"
MONTHS = 13  # the base month and a year after a change made in the second


def board():
    web = tomllib.loads(SCENARIO.read_text(encoding="utf-8"))["play"]["web"]
    rows = [(area["name"], i["row"]) for area in web["areas"] for i in area.get("indicators", [])]
    policies = [(p["label"], p["levers"][0]) for area in web["areas"] for p in area.get("policies", [])]
    return rows, policies


def step(symbol):
    spec = symbol.spec
    lo, hi = spec["range"]
    d = spec["default"]
    if symbol.type == "int" and not symbol.money:
        return d + 1 if d + 1 <= hi else d - 1
    move = (hi - lo) / 10
    value = d + move if d + move <= hi else d - move
    return round(value) if symbol.money else value


def noticeable(name, base, moved):
    if base is None or moved is None:
        return False
    if isinstance(base, bool):
        return base != moved
    if abs(base) < 1.0 and name.endswith(("rate", "share", "prevalence", "attainment", "_to_gdp", "_annual", "growth")):
        return abs(moved - base) >= 0.001
    return abs(moved - base) >= 0.01 * max(abs(base), 1e-9)


def feeds(model, rows):
    """For each row: the voters, situations and other rows its value reaches."""
    words = re.compile(r"[a-z_][a-z0-9_]*")
    readers: dict[str, set[str]] = {}
    for s in model.symbols.values():
        text = " ".join(str(s.spec.get(k, "")) for k in ("expr", "next"))
        for w in set(words.findall(text)):
            readers.setdefault(w, set()).add(s.name)
    out = {}
    for row in rows:
        seen, frontier, found = {row}, [row], set()
        for _ in range(8):
            nxt = []
            for name in frontier:
                for r in readers.get(name, ()):
                    if r in seen:
                        continue
                    seen.add(r)
                    s = model.symbols[r]
                    if s.spec.get("situation"):
                        found.add(f"situation {r}")
                    elif "voter_type" in (s.dims or []) or r in ("government_standing", "policy_standing"):
                        found.add("voters")
                    elif r in rows and r != row:
                        found.add(r)
                    else:
                        nxt.append(r)
            frontier = nxt
        out[row] = sorted(found)
    return out


def main() -> None:
    scenario = load_scenario(SCENARIO)
    model = scenario.model
    rows, policies = board()
    names = [r for _, r in rows]

    def run(levers):
        sim = Simulation(model, scenario.seed, scenario.preset, scenario.params, scenario.levers,
                         commands={1: levers} if levers else None)
        last = sim.run(MONTHS)[-1]
        return {r: last.get(r) for r in names}

    base = run({})
    movers = {r: [] for r in names}
    for label, lever in policies:
        moved = run({lever: step(model.symbols[lever])})
        for r in names:
            if noticeable(r, base[r], moved[r]):
                movers[r].append(label)
    fed = feeds(model, names)
    lines = ["# The statistics audit", "",
             "Generated by `python tools/uk/audit.py` (stage S15.2, `docs/S15-PLAN.md`, \"Statistics\"); do not edit.",
             "Each of the board's policies is moved one step in February 2025 (a level policy one level, any",
             "other a tenth of its range, a policy not in force to its first step); a statistic is moved when",
             "it is 1% away from doing nothing in January 2026, or a tenth of a point for a rate. What it feeds",
             "is read from the model's formulas, through the values in between.", "",
             "| Area | Statistic | Policies that move it | Which (first five) | Feeds |", "|---|---|---:|---|---|"]
    for area, r in rows:
        lines.append(f"| {area} | `{r}` | {len(movers[r])} | {', '.join(movers[r][:5])} | {', '.join(fed[r]) or 'nothing'} |")
    out = ROOT / "models" / "uk" / "STATISTICS.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
