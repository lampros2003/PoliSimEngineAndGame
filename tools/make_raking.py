def main() -> None:
    rng = random.Random(20261114)
    (OUT / "data").mkdir(parents=True, exist_ok=True)
    (OUT / "scenarios").mkdir(parents=True, exist_ok=True)
    rows, people, sizes = [], {}, {}
    for hid in range(1, RECORDS + 1):
        region = rng.randrange(3)
        adults = rng.choice([1, 1, 2, 2, 2, 3])
        children = rng.choice([0, 0, 0, 1, 2, 3]) if adults >= 2 else rng.choice([0, 0, 1])
        weight = rng.randint(100, 2000)
        adults_info = []
        for i in range(3):
            if i < adults:
                sex, band = rng.randrange(2), rng.choice([1, 1, 2, 2, 2, 3])
                people[(region, sex, band)] = people.get((region, sex, band), 0) + weight
            else:
                sex, band = 0, 0
            adults_info += [sex, band]
        for _ in range(children):
            sex = rng.randrange(2)
            people[(region, sex, 0)] = people.get((region, sex, 0), 0) + weight
        size = adults + children
        sizes[size] = sizes.get(size, 0) + weight
        rows.append([hid, weight, region, adults, children, size, *adults_info])
    header = ["id", "weight", "region_code", "adults", "children", "household_size", "sex1", "band1", "sex2", "band2",
              "sex3", "band3"]
    (OUT / "data" / "households.csv").write_text(
        "\n".join([",".join(header)] + [",".join(str(x) for x in r) for r in rows]) + "\n", encoding="utf-8")
    # The population is the weighted records, moved 0% to 8% away cell by cell.
    lines = ["region,sex,band,value"]
    for r, region in enumerate(REGIONS):
        for s, sex in enumerate(SEXES):
            for b, band in enumerate(BANDS):
                lines.append(f"{region},{sex},{band},{people.get((r, s, b), 0) * (1 + rng.uniform(-0.08, 0.08)):.1f}")
    (OUT / "data" / "people.csv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    lines = ["size,value"] + [f"{n},{round(sizes.get(n, 0) * (1 + rng.uniform(-0.05, 0.05)))}" for n in range(1, 7)]
    (OUT / "data" / "sizes.csv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    growth = {"child": -0.0008, "young": 0.0002, "middle": 0.0, "old": 0.0025}
    (OUT / "data" / "growth.csv").write_text(
        "band,value\n" + "".join(f"{b},{growth[b]}\n" for b in BANDS), encoding="utf-8")
    (OUT / "data" / "regional_growth.csv").write_text(
        "region,value\nnorth,-0.0003\nmidlands,0.0\nsouth,0.0004\n", encoding="utf-8")
    (OUT / "model.toml").write_text(MODEL, encoding="utf-8")
    (OUT / "scenarios" / "base.toml").write_text(
        '[scenario]\nmodel = ".."\nseed = 1\nsteps = 36\npreset = "central"\n', encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {RECORDS} households")


if __name__ == "__main__":
    main()
