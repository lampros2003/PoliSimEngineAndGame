"""Write models/cohort/: the format 1 test model (docs/spec/06-model-format-1.md).

    python tools/make_cohort.py

A synthetic population by region, sex and single year of age, ageing month by month, with
births and deaths, plus a few elements whose only purpose is to use every format 1
feature: an integer state on a range that does not start at zero, a parameter with a
column per preset, a dimensioned var read through prev(), and records of an entity that
look a value up by their region. The numbers are invented: smooth curves, not data.
"""

from __future__ import annotations

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "models" / "cohort"
REGIONS = ["north", "midlands", "south"]
SEXES = ["female", "male"]
AGES = range(0, 101)

MODEL = '''# A test model for format 1: a population by region, sex and single year of age.
# Generated by tools/make_cohort.py; the numbers are invented.

[model]
id = "cohort"
format = 1
title = "Cohort test"
currency = "GBP"
minor_units = 100
step = "month"
phases = ["people", "summary"]

[dim.region]
members = ["north", "midlands", "south"]
labels = ["The North", "The Midlands", "The South"]

[dim.sex]
members = ["female", "male"]

[dim.age]
range = [0, 100]

[dim.band]
range = [16, 20]

[entity.town]
data = "data/towns.csv"
id = "id"
weight = "weight"

[entity.town.columns.region_code]
type = "int"
unit = "1"

# ------------------------------------------------------------------ parameters

[param.mortality]
label = "Chance of dying this month"
type = "real"
unit = "1"
dims = ["sex", "age"]
data = "data/mortality.csv"
columns = { low = "low", central = "central", high = "high" }

[param.fertility]
label = "Births per woman this month"
type = "real"
unit = "1"
dims = ["age"]
data = "data/fertility.csv"

[param.boy_share]
type = "real"
unit = "1"
value = 0.512

[param.migration_rate]
label = "Net arrivals this month, per person"
type = "real"
unit = "1"
dims = ["region"]
data = "data/regions.csv"
column = "migration"

[param.local_rate]
type = "real"
unit = "1"
dims = ["region"]
value = 0.25

[param.cohort_entry]
type = "int"
unit = "person"
value = 10

[param.ageing_share]
doc = "One twelfth of a cohort has a birthday each month"
type = "real"
unit = "1"
value = 0.08333333333333333

# ------------------------------------------------------------------ the population

[var.births]
label = "Births"
type = "real"
unit = "person"
phase = "people"
dims = ["region", "sex"]
expr = "sum(population[sex: female] * fertility, age) * select(coord(sex) == 1, boy_share, 1.0 - boy_share)"

[var.deaths]
label = "Deaths"
type = "real"
unit = "person"
phase = "people"
dims = ["region", "sex", "age"]
initial = 0.0
expr = "population * mortality"

[var.arrivals]
type = "real"
unit = "person"
phase = "people"
dims = ["region", "sex", "age"]
expr = "population * migration_rate"

[state.population]
label = "Population"
type = "real"
unit = "person"
phase = "people"
dims = ["region", "sex", "age"]
initial = { data = "data/population.csv", column = "people" }
next = "population - deaths + arrivals - ageing_share * (population - deaths) + ageing_share * cohort_shift(population - deaths, age) + select(coord(age) == 0, births, 0.0)"

[state.cohort_count]
doc = "A whole-number cohort on a range that starts at 16: each step everyone moves up a band"
type = "int"
unit = "person"
phase = "people"
dims = ["band"]
initial = 1000
next = "cohort_shift(cohort_count, band) + select(coord(band) == 16, cohort_entry * coord(band), 0)"

# ------------------------------------------------------------------ summaries

[var.total_population]
label = "Population, total"
type = "real"
unit = "person"
phase = "summary"
expr = "sum(population, region, sex, age)"

[var.working_age]
label = "People aged 16 to 65"
type = "real"
unit = "person"
phase = "summary"
expr = "sum(select(coord(age) >= 16 and coord(age) <= 65, population, 0.0), age, sex, region)"

[var.women_in_the_south]
type = "real"
unit = "person"
phase = "summary"
expr = "sum(population[region: south, sex: female], age)"

[var.pensioners_by_region]
type = "real"
unit = "person"
phase = "summary"
dims = ["region"]
expr = "sum(select(coord(age) >= 66, population, 0.0), sex, age)"

[var.next_older]
doc = "Each cell reads the cell one year older (the oldest reads itself): a computed coordinate"
type = "real"
unit = "person"
phase = "summary"
dims = ["region", "sex", "age"]
expr = "population[age: min(coord(age) + 1, 100)]"

[var.next_older_total]
type = "real"
unit = "person"
phase = "summary"
expr = "sum(next_older, region, sex, age)"

[var.pensioners]
type = "real"
unit = "person"
phase = "summary"
expr = "sum(pensioners_by_region, region)"

[var.oldest_north_women]
type = "real"
unit = "person"
phase = "summary"
expr = "population[region: 0, sex: female, age: 100]"

[var.deaths_change]
type = "real"
unit = "person"
phase = "summary"
expr = "sum(deaths - prev(deaths), region, sex, age)"

[var.cohort_total]
type = "int"
unit = "person"
phase = "summary"
expr = "sum(cohort_count, band)"

[var.town_rate]
type = "real"
unit = "1"
phase = "summary"
entity = "town"
expr = "local_rate[region: region_code] * (1.0 + migration_rate[region: region_code])"

[var.town_rate_total]
type = "real"
unit = "town"
phase = "summary"
expr = "wsum(town, town_rate)"
'''

SCENARIO = '''[scenario]
model = ".."
seed = 1
steps = 36
preset = "central"
'''


def main() -> None:
    (OUT / "data").mkdir(parents=True, exist_ok=True)
    (OUT / "scenarios").mkdir(parents=True, exist_ok=True)
    (OUT / "model.toml").write_text(MODEL, encoding="utf-8", newline="\n")
    (OUT / "scenarios" / "base.toml").write_text(SCENARIO, encoding="utf-8", newline="\n")

    lines = ["sex,age,low,central,high"]
    for s, sex in enumerate(SEXES):
        for age in AGES:
            annual = min(0.5, 0.0004 * math.exp(0.085 * age) * (1.15 if s else 1.0))
            central = round(annual / 12, 9)
            lines.append(f"{sex},{age},{round(central * 0.8, 9)},{central},{round(central * 1.2, 9)}")
    (OUT / "data" / "mortality.csv").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    lines = ["age,value"]
    for age in AGES:
        rate = 0.0 if not 15 <= age <= 49 else round(0.009 * math.exp(-((age - 31) / 7) ** 2), 9)
        lines.append(f"{age},{rate}")
    (OUT / "data" / "fertility.csv").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    lines = ["region,migration"] + [f"{r},{m}" for r, m in zip(REGIONS, (0.0002, -0.0001, 0.0004))]
    (OUT / "data" / "regions.csv").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    # Written in a shuffled order, to check that cells are placed by their members.
    rows = []
    for r, region in enumerate(REGIONS):
        for s, sex in enumerate(SEXES):
            for age in AGES:
                people = round((9000 + 1500 * r) * math.exp(-age / 60) * (1.0 if age < 85 else 0.6) * (1.02 if s == 0 else 1.0), 1)
                rows.append(f"{sex},{age},{region},{people}")
    rows.sort(key=lambda line: (line.split(",")[1], line))
    (OUT / "data" / "population.csv").write_text("sex,age,region,people\n" + "\n".join(rows) + "\n",
                                                  encoding="utf-8", newline="\n")

    lines = ["id,weight,region_code", "1,40,0", "2,25,1", "3,60,2", "4,10,2"]
    (OUT / "data" / "towns.csv").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
